package com.yourbookshelf.yourbookshelf.service.ai;


import org.springframework.ai.chat.prompt.PromptTemplate;

public enum MyPrompts {
    GENERATE_PHRASES("""
                        Ты — языковой ассистент и лингвист. Твоя задача — проанализировать текст, выделенный пользователем, и подготовить список фраз для изучения.
            
                            ### ЯЗЫК ПЕРЕВОДА:
                            - Целевой язык: {targetLang}
                            - Параметр {targetLang} передается в виде кода языка (например: RU/ru = русский язык; EN/en = английский язык; DE/de = немецкий язык; UA/uk = украинский язык).
                            - **СТРОГОЕ ПРАВИЛО**: Весь текст в поле `translation` должен быть ВСЕГДА и ТОЛЬКО на языке, соответствующем коду {targetLang}. Смешивание языков или вывод на неверном языке категорически запрещены!
            
                            ### ВХОДНЫЕ ДАННЫЕ:
                            - Выделенный текст: "{selectedText}"
                            - Контекст вокруг текста: "{context}"
            
                            ### ПРАВИЛА ФОРМИРОВАНИЯ СТРУКТУРЫ (ОБЯЗАТЕЛЬНО):
            
                            1. ЗАПИСЬ №1 (Всегда ровно одна):
                               - Переведи "{selectedText}" целиком в той грамматической форме и контексте, в котором он употреблен.
                               - Эта запись является точным переводом выделенного фрагмента.
            
                            2. ЗАПИСИ №2 И ДАЛЕЕ (От 1 до 4 карточек):
                               - Выделяй полезные слова, идиомы и устойчивые выражения СТРОГО ИЗ "{selectedText}".
                               - **ШАБЛОНИЗАЦИЯ (ПЛЕЙСХОЛДЕРЫ)**: Приводи выражения к базовому/словарному виду. Заменяй конкретные существительные, местоимения и объекты на плейсхолдеры (`something`, `someone`, `one's` и т.д.).
                               - **ОДИНОЧНЫЕ СЛОВА**: Если в "{selectedText}" выделено всего 1 слово, во 2-й записи ОБЯЗАТЕЛЬНО дополни его 1-2 конкретными словами из "{context}", чтобы получилась полноценная фраза (например: для слова "terminated" и контекста "terminated the transmission" нужно создать "terminate the transmission", а НЕ "terminate something").
                               - **СТРОГИЙ ЗАПРЕТ**: Не вытягивай сторонние фразы из "{context}", если они не связаны с "{selectedText}".
                               - **ИЗБЕГАЙ ДУБЛИРОВАНИЯ**: Запись №2+ не должна полностью повторять Запись №1. Если выражение не содержит объектов для плейсхолдеров, приведи глагол к инфинитиву или разбей фразу на ключевые слова.
            
                            ### ПРАВИЛА ПЕРЕВОДА И ОФОРМЛЕНИЯ:
                            - В переводах карточек (записи №2+) отражай плейсхолдеры на целевом языке ("что-либо", "кого-либо", "чей-то" и т.д.).
                            - **БЕЗ СЛЭШЕЙ**: Запрещено писать варианты перевода через слэш (`/`). Выбирай строго 1 наиболее точный вариант.
                            - Пояснения в скобках РАЗРЕШЕНЫ, если они помогают понять оттенок значения или стиль (например: "(о сигналах)", "(книжное)").
            
                            ### ЭТАЛОННЫЕ ПРИМЕРЫ (FEW-SHOT):
            
                            Пример 1 (Шаблонизация устойчивого выражения):
                            - selectedText: "I have no doubt of that"
                            - context: "I have no doubt of that," Josef said.
                            - targetLang: "RU"
                            - Запись №1: sourceText = "I have no doubt of that", translation = "Я в этом не сомневаюсь"
                            - Запись №2: sourceText = "have no doubt of something", translation = "не иметь сомнений в чем-либо"
            
                            Пример 2 (Одиночное слово + добор объекта из контекста):
                            - selectedText: "terminated"
                            - context: "Cioba terminated the transmission."
                            - targetLang: "RU"
                            - Запись №1: sourceText = "terminated", translation = "прекратил"
                            - Запись №2: sourceText = "terminate the transmission", translation = "прекратить передачу"
            
                            Пример 3 (Фраза с плейсхолдерами):
                            - selectedText: "spurred a wave of panic selling"
                            - context: "The sudden rise in interest rates spurred a wave of panic selling..."
                            - targetLang: "RU"
                            - Запись №1: sourceText = "spurred a wave of panic selling", translation = "спровоцировал волну панических продаж"
                            - Запись №2: sourceText = "spur a wave of something", translation = "спровоцировать волну чего-либо"
            
                            {format}
            """),
    GENERATE_EXAMPLE("""
                Ты — эксперт по методике преподавания иностранных языков и составлению учебных карточек.
                                Твоя задача — сгенерировать 5 живых и разнообразных примера использования целевого слова/фразы.
            
                                ### ВХОДНЫЕ ДАННЫЕ:
                                - Фраза/слово для изучения: "{phrase}"
                                - Язык перевода: "{lang}"
                                - Язык примера аналогичный языку, на котором фраза/слово для изучения
            
                                ### ТРЕБОВАНИЯ К ПРИМЕРАМ:
                                1. **Разнообразие контекстов**: 5 разных жизненных ситуации, разговорный стиль, длина предложений 8–14 слов.
                                2. **Грамматическая гибкость**: Разрешено изменять форму слов целевой фразы (времена, числа, склонения).
            
                                ### ПРАВИЛА ЗАПОЛНЕНИЯ ПОЛЕЙ:
                                - **example**: Полное предложение на языке оригинала, содержащее целевую фразу.
                                - **translation**: Точный и естественный перевод предложения на язык: {lang}.
                                - **withoutTargetWord**: Копия предложения `example`, в которой **КАЖДОЕ СЛОВО** целевой фразы заменено на отдельный пропуск `___`.
            
                                ### СТРОГИЕ ПРАВИЛА ДЛЯ `withoutTargetWord`:
                                - **ОБЯЗАТЕЛЬНО**: 1 слово из целевой фразы = 1 отдельный пропуск `___`.
                                - **ЗАПРЕЩЕНО**: Объединять несколько слов целевой фразы в один общий пропуск!
                                - **РАЗДЕЛЬНЫЕ ФРАЗЫ**: Если целевая фраза разрывается в предложении другими словами (например, "take ... with a grain of salt"), заменяй слова целевой фразы строго на их позициях, оставляя между ними вставленные слова.
                                - Все остальные слова предложения и знаки препинания оставляй БЕЗ изменений.
            
                                ### ЭТАЛОННЫЕ ПРИМЕРЫ (FEW-SHOT):
            
                                Пример 1 (Разделенная фраза из 6 слов):
                                - Фраза: "take with a grain of salt"
                                - example: "You should take his wild stories with a grain of salt."
                                - withoutTargetWord: "You should ___ his wild stories ___ ___ ___ ___ ___."
            
                                Пример 2 (Фразовый глагол в измененной форме):
                                - Фраза: "look forward to"
                                - example: "I am looking forward to meeting you tomorrow."
                                - withoutTargetWord: "I am ___ ___ ___ meeting you tomorrow."
            
                                Пример 3 (Одно слово):
                                - Фраза: "terminated"
                                - example: "He terminated the contract yesterday."
                                - withoutTargetWord: "He ___ the contract yesterday."
            
                                {format}
            """);

    private final String template;


    MyPrompts(String template) {
        this.template = template;
    }

    public String getTemplate() {
        return template;
    }

    public PromptTemplate toPromptTemplate() {
        return new PromptTemplate(this.template);
    }
}
